const CORS = {
    "Access-Control-Allow-Origin": "*",
    "Access-Control-Allow-Methods": "POST, OPTIONS",
    "Access-Control-Allow-Headers": "Content-Type, Cache-Control, Pragma",
    "Content-Type": "application/json",
};

module.exports.handler = async function (event, context) {
    if (event.httpMethod === "OPTIONS") {
        return {
            statusCode: 204,
            headers: {
                "Access-Control-Allow-Origin": "*",
                "Access-Control-Allow-Methods": "POST, OPTIONS",
                "Access-Control-Allow-Headers": "Content-Type, Cache-Control, Pragma",
            },
            body: "",
        };
    }

    if (event.httpMethod !== "POST") {
        return { statusCode: 405, headers: CORS, body: JSON.stringify({ error: "Method not allowed" }) };
    }

    let body;
    try {
        body = JSON.parse(event.body);
    } catch {
        return { statusCode: 400, headers: CORS, body: JSON.stringify({ error: "Invalid JSON" }) };
    }

    const { message, history = [], catalog = "" } = body;

    if (!message || typeof message !== "string" || !message.trim()) {
        return { statusCode: 400, headers: CORS, body: JSON.stringify({ error: "Сообщение обязательно" }) };
    }
    if (message.length > 1500) {
        return { statusCode: 400, headers: CORS, body: JSON.stringify({ error: "Макс 1500 символов" }) };
    }

    const catalogText = typeof catalog === "string" ? catalog.slice(0, 50000) : "";
    const systemPrompt = buildSystemPrompt(catalogText);

    const trimmedHistory = Array.isArray(history) ? history.slice(-20) : [];
    const messages = [
        {
            role: "system",
            content: [{ type: "text", text: systemPrompt, cache_control: { type: "ephemeral" } }],
        },
        ...trimmedHistory,
        { role: "user", content: message.trim() },
    ];

    // Fallback-цепочка моделей. OpenRouter принимает массив `models` до 3 шт:
    // если первая ошибается / таймаутит / rate-limited, автоматически пробует
    // следующую. Все НЕ блокируют российские IP (OpenRouter проксирует через
    // US/EU). Anthropic Claude не включаем — единственный кто режет РФ-трафик.
    //
    //   1. Gemini 2.0 Flash       ~$0.10/$0.40 — основная (быстро + дёшево)
    //   2. GPT-4o (полный)        ~$2.5/$10    — мощный fallback при сбое Google
    //   3. Llama 3.3 70B Instruct ~$0.13/$0.40 — open-source, последний бекап
    const MODEL_FALLBACKS = [
        "google/gemini-2.0-flash-001",
        "openai/gpt-4o",
        "meta-llama/llama-3.3-70b-instruct",
    ];

    let response;
    try {
        response = await fetch(OPENROUTER_URL, {
            method: "POST",
            headers: {
                "Authorization": `Bearer ${process.env.OPENROUTER_API_KEY}`,
                "Content-Type": "application/json",
                "HTTP-Referer": "https://kokolsk1y.github.io/zalassist/",
                "X-Title": "ZalAssist",
            },
            body: JSON.stringify({
                model: MODEL_FALLBACKS[0],
                models: MODEL_FALLBACKS,
                messages,
                stream: false,
                max_tokens: 1500,
                temperature: 0.3,
            }),
        });
    } catch {
        return { statusCode: 502, headers: CORS, body: JSON.stringify({ error: "Не удалось подключиться к ИИ-сервису" }) };
    }

    if (!response.ok) {
        const errText = await response.text().catch(() => "");
        return { statusCode: 502, headers: CORS, body: JSON.stringify({ error: "ИИ-сервис временно недоступен", status: response.status, detail: errText }) };
    }

    const data = await response.json();
    const text = data.choices?.[0]?.message?.content || "";
    return { statusCode: 200, headers: CORS, body: JSON.stringify({ text }) };
};
